#!/usr/bin/env python3
"""Patch Flutter-generated Android Kotlin DSL for Firebase Spark exhibition.

This script operates on the disposable Android project generated by flutter
create. It never includes google-services.json in Git-tracked source.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1] / "app"
android = root / "android"
app = android / "app"
g_app = app / "build.gradle.kts"
g_settings = android / "settings.gradle.kts"
manifest = app / "src" / "main" / "AndroidManifest.xml"

for path in (g_app, g_settings, manifest):
    if not path.is_file():
        raise SystemExit(f"Missing Flutter-generated Android file: {path}")

def add_plugin(text: str, entry: str) -> str:
    if entry.split('")')[0] + '")' in text:
        return text
    plugins = re.search(r"(?m)^plugins\s*\{", text)
    if not plugins:
        raise ValueError("Android plugins block not found")
    return text[:plugins.end()] + "\n    " + entry + text[plugins.end():]

text = g_settings.read_text()
text = add_plugin(text, 'id("com.google.gms.google-services") version "4.5.0" apply false')
g_settings.write_text(text)

text = g_app.read_text()
text = add_plugin(text, 'id("com.google.gms.google-services")')
text, count = re.subn(r'applicationId\s*=\s*"[^"]+"', 'applicationId = "app.fmate"', text)
if count != 1:
    raise SystemExit("Unable to set exact app.fmate applicationId")
text = text.replace("minSdk = flutter.minSdkVersion", "minSdk = 24")
g_app.write_text(text)

text = manifest.read_text()
if 'android.permission.INTERNET' not in text:
    text = re.sub(r'(<manifest\b[^>]*>)', r'\1\n    <uses-permission android:name="android.permission.INTERNET" />', text, count=1)
if 'android:usesCleartextTraffic=' not in text:
    text, count = re.subn(r'(<application\b)', r'\1 android:usesCleartextTraffic="true"', text, count=1)
    if count != 1:
        raise SystemExit("Android application tag missing")
text = re.sub(r'android:label="[^"]*"', 'android:label="F-Mate"', text, count=1)
if 'android:scheme="fmate"' not in text:
    marker = '</activity>'
    if marker not in text:
        raise SystemExit("Flutter MainActivity marker not found")
    filter_xml = """    <intent-filter>
                <action android:name="android.intent.action.VIEW"/>
                <category android:name="android.intent.category.DEFAULT"/>
                <category android:name="android.intent.category.BROWSABLE"/>
                <data android:scheme="fmate" android:host="payment"/>
            </intent-filter>
        """
    text = text.replace(marker, filter_xml + marker, 1)
manifest.write_text(text)
print("Firebase Android configuration: app.fmate, SDK24, Google Services 4.5.0, Toss deep link.")
